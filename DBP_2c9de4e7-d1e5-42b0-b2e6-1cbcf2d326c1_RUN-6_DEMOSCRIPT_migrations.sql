CREATE OR REPLACE PROCEDURE "FINDB_PROD"."CORE_BANKING"."SP_CALCULATE_INTEREST"("P_CALCULATION_DATE" DATE DEFAULT null)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS $$
DECLARE
    v_calc_date DATE;
BEGIN
    v_calc_date := COALESCE(:P_CALCULATION_DATE, CURRENT_DATE());

    -- Compound daily: balance × ((1 + rate/365)^1 − 1)
    MERGE INTO ACCOUNTS A
    USING (
        SELECT
            A2.ACCOUNT_ID,
            A2.CURRENT_BALANCE * (POWER(1 + IR.ANNUAL_RATE / 365.0, 1) - 1) AS DAILY_INTEREST
        FROM ACCOUNTS A2
        JOIN PRODUCTS P
            ON  P.PRODUCT_ID = A2.PRODUCT_ID
        JOIN INTEREST_RATES IR
            ON  IR.PRODUCT_CODE   = P.PRODUCT_CODE
            AND IR.EFFECTIVE_DATE <= :v_calc_date
            AND (IR.END_DATE IS NULL OR IR.END_DATE >= :v_calc_date)
        WHERE A2.ACCOUNT_STATUS = 'ACTIVE'
          AND A2.ACCOUNT_TYPE   IN ('SAVINGS', 'MONEY_MARKET', 'CD')
          AND A2.CURRENT_BALANCE > 0
    ) CALC ON (A.ACCOUNT_ID = CALC.ACCOUNT_ID)
    WHEN MATCHED THEN UPDATE SET
        A.CURRENT_BALANCE   = A.CURRENT_BALANCE   + CALC.DAILY_INTEREST,
        A.AVAILABLE_BALANCE = A.AVAILABLE_BALANCE + CALC.DAILY_INTEREST,
        A.UPDATED_AT        = CURRENT_TIMESTAMP();

    RETURN 'Compound interest accrual complete: ' || SQLROWCOUNT
           || ' accounts updated on ' || :v_calc_date;
END;
$$;

CREATE OR REPLACE PROCEDURE "FINDB_PROD"."CORE_BANKING"."SP_PROCESS_LOAN_PAYMENT"("P_LOAN_ID" NUMBER(38,0), "P_PAYMENT_AMOUNT" NUMBER(38,0), "P_PAYMENT_METHOD" VARCHAR DEFAULT 'ACH')
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS $$
DECLARE
    v_loan_balance   NUMBER;
    v_interest_rate  NUMBER;
    v_account_id     NUMBER;
    v_avail_balance  NUMBER;
    v_interest       NUMBER;
    v_principal      NUMBER;
    v_payment_id     NUMBER;
BEGIN
    SELECT OUTSTANDING_BALANCE, INTEREST_RATE, ACCOUNT_ID
    INTO   :v_loan_balance, :v_interest_rate, :v_account_id
    FROM   LOANS
    WHERE  LOAN_ID = :P_LOAN_ID AND LOAN_STATUS = 'CURRENT';

    -- DEV: overdraft guard — fail fast if insufficient funds
    SELECT AVAILABLE_BALANCE
    INTO   :v_avail_balance
    FROM   ACCOUNTS
    WHERE  ACCOUNT_ID = :v_account_id;

    IF (:v_avail_balance < :P_PAYMENT_AMOUNT) THEN
        RETURN 'ERROR: Insufficient funds — available $'
               || :v_avail_balance || ', required $' || :P_PAYMENT_AMOUNT;
    END IF;

    v_interest  := ROUND(:v_loan_balance * :v_interest_rate / 12.0, 2);
    v_principal := :P_PAYMENT_AMOUNT - :v_interest;

    SELECT COALESCE(MAX(PAYMENT_ID), 0) + 1
    INTO   :v_payment_id
    FROM   LOAN_PAYMENTS;

    INSERT INTO LOAN_PAYMENTS (
        PAYMENT_ID, LOAN_ID, PAYMENT_DATE, PAYMENT_AMOUNT,
        PRINCIPAL_PORTION, INTEREST_PORTION, PAYMENT_METHOD, PAYMENT_STATUS
    ) VALUES (
        :v_payment_id, :P_LOAN_ID, CURRENT_DATE(), :P_PAYMENT_AMOUNT,
        :v_principal, :v_interest, :P_PAYMENT_METHOD, 'COMPLETED'
    );

    UPDATE LOANS
    SET  OUTSTANDING_BALANCE = OUTSTANDING_BALANCE - :v_principal,
         LOAN_STATUS         = IFF(OUTSTANDING_BALANCE - :v_principal <= 0, 'PAID_OFF', 'CURRENT'),
         UPDATED_AT          = CURRENT_TIMESTAMP()
    WHERE LOAN_ID = :P_LOAN_ID;

    RETURN 'Payment $' || :P_PAYMENT_AMOUNT || ' applied to loan ' || :P_LOAN_ID
           || ' (principal $' || :v_principal || ', interest $' || :v_interest || ')';
END;
$$;

