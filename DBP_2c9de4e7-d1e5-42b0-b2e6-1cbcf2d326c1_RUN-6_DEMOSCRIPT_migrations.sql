CREATE OR REPLACE DYNAMIC TABLE DT_ACCOUNT_BALANCE_SUMMARY target_lag = '1 minute' warehouse = COMPUTE_WH
 COMMENT='Near-real-time account balance rollup — refreshed every minute'
  DATA_RETENTION_TIME_IN_DAYS = 1
  MAX_DATA_EXTENSION_TIME_IN_DAYS = 14
AS
SELECT
    A.ACCOUNT_ID,
    A.CUSTOMER_ID,
    A.ACCOUNT_NUMBER,
    A.ACCOUNT_TYPE,
    A.CURRENT_BALANCE                   AS BOOK_BALANCE,
    COALESCE(SUM(
        CASE
            WHEN T.TRANSACTION_TYPE IN ('DEPOSIT',    'CREDIT') THEN  T.AMOUNT
            WHEN T.TRANSACTION_TYPE IN ('WITHDRAWAL', 'DEBIT')  THEN -T.AMOUNT
            ELSE 0
        END
    ), 0)                               AS POSTED_ACTIVITY,
    COUNT(T.TRANSACTION_ID)             AS TRANSACTION_COUNT,
    MAX(T.TRANSACTION_DATE)             AS LAST_TRANSACTION_AT,
    CURRENT_TIMESTAMP()                 AS LAST_REFRESHED_AT
FROM ACCOUNTS A
LEFT JOIN TRANSACTIONS T
    ON  T.ACCOUNT_ID = A.ACCOUNT_ID
    AND T.STATUS     = 'POSTED'
    AND T.TRANSACTION_DATE >= DATEADD('day', -1, CURRENT_TIMESTAMP())
WHERE A.ACCOUNT_STATUS = 'ACTIVE'
GROUP BY A.ACCOUNT_ID, A.CUSTOMER_ID, A.ACCOUNT_NUMBER, A.ACCOUNT_TYPE, A.CURRENT_BALANCE;

